#!/usr/bin/env node
// Writes Sources/IslaKit/UI/Hugeicons.swift: the Hugeicons drawings Isla's
// glyphs use, as Swift data. Run by hand, never by a gate, whenever a recipe in
// Sources/IslaKit/UI/IslandGlyph.swift starts or stops naming an icon.
//
//   npm pack @hugeicons/core-free-icons@4.4.0     # in an empty folder
//   tar -xzf hugeicons-core-free-icons-4.4.0.tgz
//   node Scripts/vendor-hugeicons.mjs <that folder>/package
//
// The package's files are read as text and never imported, so nothing in the
// download runs. The icons named are exactly the `Hugeicons.<name>` references
// in IslandGlyph.swift, so the table can neither miss one nor carry a spare.
// An icon that needs something the Swift side does not draw (an arc, a
// transform, an opacity) stops the script rather than shipping a glyph with a
// piece missing.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const packageDir = process.argv[2];
if (!packageDir) {
  console.error("usage: node Scripts/vendor-hugeicons.mjs <unpacked @hugeicons/core-free-icons package>");
  process.exit(2);
}

const manifest = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));
if (manifest.name !== "@hugeicons/core-free-icons" || manifest.version !== "4.4.0") {
  console.error(`expected @hugeicons/core-free-icons 4.4.0, found ${manifest.name} ${manifest.version}`);
  process.exit(1);
}

const recipes = readFileSync(join(root, "Sources/IslaKit/UI/IslandGlyph.swift"), "utf8");
const names = [...new Set([...recipes.matchAll(/\bHugeicons\.`?([a-z][A-Za-z0-9]*)`?/g)].map((m) => m[1]))].sort();
// A drawing named after a Swift keyword (Repeat) is declared in backticks and
// referred to as Hugeicons.`repeat`.
const swiftKeywords = new Set(["repeat", "default", "case", "switch", "return", "import", "class", "struct", "protocol", "operator", "in", "is", "as", "for", "while", "if", "else", "guard", "defer", "do", "try", "throw", "catch", "func", "let", "var", "init", "self", "super", "nil", "true", "false", "where", "break", "continue", "fallthrough", "enum", "extension", "subscript", "static", "public", "private", "internal", "fileprivate", "open", "inout", "deinit", "typealias", "associatedtype", "any", "some"]);
const declared = (name) => (swiftKeywords.has(name) ? `\`${name}\`` : name);

const numberAttr = (attrs, key, icon) => {
  const value = attrs[key];
  if (value === undefined || !/^-?[0-9.]+$/.test(value)) throw new Error(`${icon}: ${key}="${value}"`);
  return value;
};

const out = [];
for (const name of names) {
  const icon = `${name[0].toUpperCase()}${name.slice(1)}Icon`;
  const file = join(packageDir, "dist/esm", `${icon}.js`);
  if (!existsSync(file)) throw new Error(`${icon} is not in Hugeicons 4.4.0`);
  const source = readFileSync(file, "utf8");
  const elements = [...source.matchAll(/\["(\w+)", \{([^}]*)\}\]/g)].map((m) => {
    const attrs = Object.fromEntries([...m[2].matchAll(/(\w+): "([^"]*)"/g)].map((a) => [a[1], a[2]]));
    return [m[1], attrs];
  });
  if (elements.length === 0) throw new Error(`${icon}: no elements read`);
  const lines = elements.map(([tag, attrs]) => {
    for (const key of ["transform", "opacity"]) {
      if (key in attrs) throw new Error(`${icon}: ${tag} has ${key}, which the Swift renderer does not draw`);
    }
    switch (tag) {
      case "path": {
        const d = attrs.d;
        const unsupported = d.replace(/[eE][-+]?\d/g, "").match(/[^MmLlHhVvCcZz0-9.,\s-]/);
        if (unsupported) throw new Error(`${icon}: path command "${unsupported[0]}" is not read by SVGPath`);
        const evenOdd = attrs.fillRule === "evenodd" ? ", evenOdd: true" : "";
        return `.path("${d}"${evenOdd})`;
      }
      case "circle":
        return `.circle(cx: ${numberAttr(attrs, "cx", icon)}, cy: ${numberAttr(attrs, "cy", icon)}, r: ${numberAttr(attrs, "r", icon)})`;
      case "ellipse":
        return `.ellipse(cx: ${numberAttr(attrs, "cx", icon)}, cy: ${numberAttr(attrs, "cy", icon)}, rx: ${numberAttr(attrs, "rx", icon)}, ry: ${numberAttr(attrs, "ry", icon)})`;
      case "rect": {
        const rx = attrs.rx === undefined ? "" : `, rx: ${numberAttr(attrs, "rx", icon)}`;
        return `.rect(x: ${attrs.x ?? "0"}, y: ${attrs.y ?? "0"}, width: ${numberAttr(attrs, "width", icon)}, height: ${numberAttr(attrs, "height", icon)}${rx})`;
      }
      default:
        throw new Error(`${icon}: element <${tag}> is not drawn by GlyphElement`);
    }
  });
  out.push(`    /// \`${icon}\`\n    static let ${declared(name)}: [GlyphElement] = [\n${lines.map((l) => `        ${l},`).join("\n")}\n    ]`);
}

const header = `// Generated by Scripts/vendor-hugeicons.mjs from @hugeicons/core-free-icons
// 4.4.0 (MIT, Copyright (c) 2025 Hugeicons; see THIRD_PARTY_NOTICES.md).
// Do not edit: change the recipes in IslandGlyph.swift and run the script.

import CoreGraphics

/// The Hugeicons free drawings Isla's glyphs are made from, on their 24 unit
/// grid, element by element in the order the package draws them (recipes pick
/// and style elements by that index).
enum Hugeicons {
`;
writeFileSync(join(root, "Sources/IslaKit/UI/Hugeicons.swift"), `${header}${out.join("\n\n")}\n}\n`);
console.log(`wrote ${names.length} icons`);
